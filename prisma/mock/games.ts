import type { PhaseType, SideType } from "@/types/game";

export const mapStats = (stats: number[]) => {
  const [
    seconds,
    fgMade,
    fgAttempted,
    fg3Made,
    fg3Attempted,
    ftMade,
    ftAttempted,
    points,
    offRebounds,
    defRebounds,
    rebounds,
    assists,
    steals,
    blocks,
    turnovers,
    personalFouls,
    technicalFouls,
  ] = stats;

  return {
    seconds,
    fgMade,
    fgAttempted,
    fg3Made,
    fg3Attempted,
    ftMade,
    ftAttempted,
    points: fgMade * 2 + fg3Made + fgMade,
    offRebounds,
    defRebounds,
    rebounds: offRebounds + defRebounds,
    assists,
    steals,
    blocks,
    turnovers,
    personalFouls,
    technicalFouls,
  }
};

